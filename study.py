def _rows_to_csv(header, rows):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(header)
    w.writerows(rows)
    return buf.getvalue()


def export_participants_csv():
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("""SELECT code, arm, cohort, consent_version, consented_at,
                              enrolled_at, withdrawn_at FROM study_participants
                       ORDER BY enrolled_at""")
        rows = cur.fetchall()
    return _rows_to_csv(
        ["code", "arm", "cohort", "consent_version", "consented_at",
         "enrolled_at", "withdrawn_at"], rows)


def export_events_csv():
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("""SELECT e.code, p.arm, e.session_id, e.event_type,
                              e.payload, e.client_ts, e.server_ts
                       FROM study_events e
                       LEFT JOIN study_participants p ON p.code = e.code
                       ORDER BY e.code, e.server_ts""")
        rows = cur.fetchall()
    return _rows_to_csv(
        ["code", "arm", "session_id", "event_type", "payload",
         "client_ts", "server_ts"], rows)


def export_responses_csv():
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("""SELECT r.code, p.arm, r.instrument, r.timepoint,
                              r.item_id, r.value, r.responded_at
                       FROM study_responses r
                       LEFT JOIN study_participants p ON p.code = r.code
                       ORDER BY r.code, r.instrument, r.timepoint, r.item_id""")
        rows = cur.fetchall()
    return _rows_to_csv(
        ["code", "arm", "instrument", "timepoint", "item_id", "value",
         "responded_at"], rows)


def export_decisions_csv():
    """Decision-level telemetry joined to arm — the primary behavioural outcome."""
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("""SELECT s.session_id, s.persona, s.difficulty, s.choice,
                              s.decision_index, s.wellbeing, s.zone,
                              s.archetype_expected, s.gap, s.trigger_kind,
                              s.characteristic_drift, s.created_at
                       FROM scenario_choices s
                       ORDER BY s.session_id, s.decision_index""")
        rows = cur.fetchall()
    return _rows_to_csv(
        ["session_id", "persona", "difficulty", "choice", "decision_index",
         "wellbeing", "zone", "archetype_expected", "gap", "trigger_kind",
         "characteristic_drift", "created_at"], rows)


def export_calibration_csv():
    """
    Per-decision calibration record: the primary dataset for the calibration
    claim. One row per decision with the full experiential cycle attached.
    """
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("""SELECT session_id, decision_index, persona, principle, surface,
                              dlo_band, dlo_score, titration, predicted,
                              prediction_correct, confidence, surprise, c_level,
                              wellbeing, zone, gap, characteristic_drift, created_at
                       FROM scenario_choices
                       WHERE principle IS NOT NULL
                       ORDER BY session_id, decision_index""")
        rows = cur.fetchall()
    return _rows_to_csv(
        ["session_id", "decision_index", "persona", "principle", "surface",
         "dlo_band", "dlo_score", "titration", "predicted", "prediction_correct",
         "confidence", "surprise", "c_level", "wellbeing", "zone", "gap",
         "characteristic_drift", "created_at"], rows)


def study_summary():
    """Recruitment and completion monitoring for the researcher dashboard."""
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute("SELECT arm, COUNT(*) FROM study_participants WHERE withdrawn_at IS NULL GROUP BY arm")
        by_arm = {r[0]: r[1] for r in cur.fetchall()}
        cur.execute("SELECT COUNT(*) FROM study_participants WHERE consented_at IS NOT NULL AND withdrawn_at IS NULL")
        consented = cur.fetchone()[0]
        cur.execute("SELECT COUNT(*) FROM study_participants WHERE withdrawn_at IS NOT NULL")
        withdrawn = cur.fetchone()[0]
        cur.execute("SELECT COUNT(*) FROM study_events")
        events = cur.fetchone()[0]
        cur.execute("""SELECT timepoint, COUNT(DISTINCT code) FROM study_responses
                       GROUP BY timepoint""")
        by_tp = {r[0]: r[1] for r in cur.fetchall()}
        cur.execute("SELECT COUNT(DISTINCT code) FROM study_events")
        active = cur.fetchone()[0]
    return {
        "by_arm": by_arm,
        "consented": consented,
        "withdrawn": withdrawn,
        "events": events,
        "active_participants": active,
        "responses_by_timepoint": by_tp,
        "consent_version": CONSENT_VERSION,
    }
