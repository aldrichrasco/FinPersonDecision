def init_study_tables():
    autoinc = "GENERATED BY DEFAULT AS IDENTITY" if db.IS_POSTGRES else "AUTOINCREMENT"
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(f"""
            CREATE TABLE IF NOT EXISTS study_participants (
                id INTEGER PRIMARY KEY {autoinc},
                code TEXT UNIQUE NOT NULL,
                arm TEXT NOT NULL,
                cohort TEXT,
                consent_version TEXT,
                consented_at REAL,
                enrolled_at REAL,
                withdrawn_at REAL
            )""")
        cur.execute(f"""
            CREATE TABLE IF NOT EXISTS study_events (
                id INTEGER PRIMARY KEY {autoinc},
                code TEXT NOT NULL,
                session_id TEXT,
                event_type TEXT NOT NULL,
                payload TEXT,
                client_ts REAL,
                server_ts REAL
            )""")
        cur.execute(f"""
            CREATE TABLE IF NOT EXISTS study_responses (
                id INTEGER PRIMARY KEY {autoinc},
                code TEXT NOT NULL,
                instrument TEXT NOT NULL,
                timepoint TEXT NOT NULL,
                item_id TEXT NOT NULL,
                value TEXT,
                responded_at REAL
            )""")
        # Indexes matter once event volume grows.
        for stmt in [
            "CREATE INDEX IF NOT EXISTS idx_events_code ON study_events(code)",
            "CREATE INDEX IF NOT EXISTS idx_events_ts ON study_events(server_ts)",
            "CREATE INDEX IF NOT EXISTS idx_resp_code ON study_responses(code)",
        ]:
            try:
                cur.execute(stmt)
            except Exception:
                pass


# --------------------------------------------------------------------------
# Assignment
# --------------------------------------------------------------------------

def assign_arm(code):
    """
    Deterministic arm assignment by hash of the study code.

    Deterministic rather than random so that assignment is reproducible and
    auditable: given a code list, an independent party can verify allocation
    without database access. Codes are issued in advance, so this is
    equivalent to pre-randomisation provided codes are generated randomly.

    A code prefixed 'S<n>-' forces stratum n's arm, supporting stratified
    allocation (e.g. by baseline distortion status, per paper §8.4).
    """
    if not code:
        return ARM_FULL
    digest = hashlib.sha256(code.strip().upper().encode()).hexdigest()
    return ARMS[int(digest[:8], 16) % len(ARMS)]


def features_for(code):
    p = get_participant(code)
    arm = p["arm"] if p else ARM_FULL
    return {"arm": arm, **ARM_FEATURES.get(arm, ARM_FEATURES[ARM_FULL])}


# --------------------------------------------------------------------------
# Participants
# --------------------------------------------------------------------------

def enrol(code, cohort=None):
    """Creates a participant record. Idempotent — re-entry returns existing."""
    code = (code or "").strip().upper()
    if not code or len(code) > 40:
        return None
    existing = get_participant(code)
    if existing:
        return existing
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"""INSERT INTO study_participants
                (code, arm, cohort, consent_version, enrolled_at)
                VALUES ({db._ph(5)})""",
            (code, assign_arm(code), cohort, None, time.time()),
        )
    return get_participant(code)


def get_participant(code):
    code = (code or "").strip().upper()
    if not code:
        return None
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"""SELECT code, arm, cohort, consent_version, consented_at,
                       enrolled_at, withdrawn_at
                FROM study_participants WHERE code = {db._ph(1)}""",
            (code,),
        )
        r = cur.fetchone()
        if not r:
            return None
        return {
            "code": r[0], "arm": r[1], "cohort": r[2],
            "consent_version": r[3], "consented_at": r[4],
            "enrolled_at": r[5], "withdrawn_at": r[6],
        }


def record_consent(code):
    """Records consent under the current version. Required before any capture."""
    p = enrol(code)
    if not p:
        return None
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"""UPDATE study_participants
                SET consent_version = {db._ph(1)}, consented_at = {db._ph(1)}
                WHERE code = {db._ph(1)}""",
            (CONSENT_VERSION, time.time(), p["code"]),
        )
    return get_participant(p["code"])


def has_valid_consent(code):
    p = get_participant(code)
    return bool(
        p and not p["withdrawn_at"]
        and p["consented_at"]
        and p["consent_version"] == CONSENT_VERSION
    )


def withdraw(code):
    """Hard-deletes all research data for a participant. Not a soft flag."""
    code = (code or "").strip().upper()
    if not code:
        return False
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(f"DELETE FROM study_events WHERE code = {db._ph(1)}", (code,))
        cur.execute(f"DELETE FROM study_responses WHERE code = {db._ph(1)}", (code,))
        cur.execute(f"DELETE FROM study_participants WHERE code = {db._ph(1)}", (code,))
    return True


