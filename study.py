# Allow-list. An unknown event type is dropped rather than stored, so the
# event table cannot be used as arbitrary client-controlled storage.
EVENT_TYPES = {
    "session_start", "session_end",
    "situation_selected", "quiz_started", "quiz_completed",
    "scenario_shown", "decision_made", "scenario_rerolled",
    "round_completed", "recap_dismissed",
    "archetype_inferred", "archetype_reassigned",
    "coach_message_sent", "coach_reply_received",
    "drawer_opened", "drawer_closed",
    "chart_inspected", "help_opened", "safeguarding_shown",
    "instrument_started", "instrument_completed",
    "page_view", "idle_timeout",
    # Experiential cycle
    "prediction_made", "prediction_skipped",
    "surprise_rated", "reflection_written", "reflection_skipped",
    "recognition_classified", "dlo_estimated", "titration_applied",
}

MAX_PAYLOAD_CHARS = 4000


def log_event(code, session_id, event_type, payload=None, client_ts=None):
    if event_type not in EVENT_TYPES:
        return False
    if not has_valid_consent(code):
        return False
    body = ""
    if payload is not None:
        try:
            body = json.dumps(payload)[:MAX_PAYLOAD_CHARS]
        except (TypeError, ValueError):
            body = ""
    with db._conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"""INSERT INTO study_events
                (code, session_id, event_type, payload, client_ts, server_ts)
                VALUES ({db._ph(6)})""",
            (code.strip().upper(), str(session_id or "")[:64], event_type,
             body, float(client_ts) if client_ts else None, time.time()),
        )
    return True


def save_responses(code, instrument, timepoint, responses):
    """
    Stores instrument responses. `responses` maps item_id -> value.

    Item content is NOT stored here — only identifiers and values — so that
    licensed instruments can be administered without their items entering
    this repository.
    """
    if not has_valid_consent(code):
        return 0
    if timepoint not in TIMEPOINTS:
        return 0
    if not isinstance(responses, dict):
        return 0
    now = time.time()
    n = 0
    with db._conn() as conn:
        cur = conn.cursor()
        for item_id, value in list(responses.items())[:200]:
            cur.execute(
                f"""INSERT INTO study_responses
                    (code, instrument, timepoint, item_id, value, responded_at)
                    VALUES ({db._ph(6)})""",
                (code.strip().upper(), str(instrument)[:64], timepoint,
                 str(item_id)[:64], str(value)[:200], now),
            )
            n += 1
    return n


