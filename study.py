"""
Study infrastructure for evaluation capture.

Supports the three-phase evaluation design: formative usability, construct
validation, and a randomised efficacy trial with ablation arms.

DESIGN COMMITMENTS

1. PSEUDONYMISATION. Participants are identified by a study code only. No
   name, email or account is required or stored. If a participant also has a
   platform account, the two are never linked in the research tables.

2. CONSENT IS A GATE. No research data is written before recorded consent.
   Consent is versioned, so a protocol amendment invalidates prior consent
   rather than silently inheriting it.

3. WITHDRAWAL IS REAL. Withdrawal deletes all research data for that
   participant, not a flag on a retained row.

4. DETERMINISTIC ASSIGNMENT. Condition is derived from the study code by
   hash, so assignment is reproducible, auditable, and cannot drift if the
   database is rebuilt. Stratification is supported via code prefixes.

5. EVENT-LEVEL CAPTURE. Analysis needs sequence and timing, not aggregates.
   Every interaction is a timestamped row.
"""

import csv
import hashlib
import io
import json
import os
import time

import db

# Bump when the information sheet or protocol changes. Participants consented
# under an older version are excluded from data collection until re-consent.
CONSENT_VERSION = os.environ.get("CONSENT_VERSION", "1.0")

# Study arms for the efficacy trial (paper §8.4, Phase 3).
ARM_FULL = "full"          # complete artefact
ARM_ABLATED = "ablated"    # personalisation + characteristic drift disabled
ARM_CONTROL = "control"    # information only, no sandbox

ARMS = [ARM_FULL, ARM_ABLATED, ARM_CONTROL]

# Which capabilities each arm exposes. Read by the client to gate features,
# and by analysis to confirm what a participant was actually shown.
ARM_FEATURES = {
    ARM_FULL: {
        "sandbox": True, "personalisation": True, "characteristic_drift": True,
        "adaptive_scenarios": True, "coach": True, "observations": True,
    },
    ARM_ABLATED: {
        # Same surface, same time on task, mechanisms removed. This isolates
        # the theorised mechanisms from attention and engagement effects.
        "sandbox": True, "personalisation": False, "characteristic_drift": False,
        "adaptive_scenarios": False, "coach": True, "observations": False,
    },
    ARM_CONTROL: {
        "sandbox": False, "personalisation": False, "characteristic_drift": False,
        "adaptive_scenarios": False, "coach": False, "observations": False,
    },
}

# Phases a participant moves through. Timepoints are recorded so repeated
# measures can be aligned even if participants complete them out of order.
TIMEPOINTS = ["baseline", "post", "followup"]


