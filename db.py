import sqlite3
import time
from contextlib import contextmanager

DATABASE_URL = os.environ.get("DATABASE_URL", "")
SQLITE_PATH = os.environ.get("SQLITE_PATH", "finperson.db")

IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

if IS_POSTGRES:
    import psycopg
    # Render's DATABASE_URL sometimes uses the deprecated postgres:// scheme.
    _PG_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)


@contextmanager
def _conn():
    if IS_POSTGRES:
        with psycopg.connect(_PG_URL) as conn:
            yield conn
    else:
        conn = sqlite3.connect(SQLITE_PATH)
        conn.row_factory = sqlite3.Row
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()


def _ph(n):
    """Placeholder string: %s for postgres, ? for sqlite."""
    mark = "%s" if IS_POSTGRES else "?"
    return ", ".join([mark] * n)


def ping():
    """Cheapest possible round-trip to confirm the database is reachable —
    for /health, which may be polled every few seconds. Raises on failure;
    the caller decides what that means for the response."""
    with _conn() as conn:
        conn.cursor().execute("SELECT 1")


