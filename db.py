def upsert_subscription(user_id, provider, provider_customer_id, provider_subscription_id,
                         plan, status, current_period_end):
    """First thing that ever writes to `subscriptions` (see the DDL comment
    in init_db()) — called from the Stripe webhook handler. Keyed on
    provider_subscription_id so repeated webhook deliveries for the same
    subscription (Stripe retries on any non-2xx) update the same row instead
    of creating duplicates."""
    now = time.time()
    with _conn() as conn:
        cur = conn.cursor()
        mark = "%s" if IS_POSTGRES else "?"
        cur.execute(
            f"SELECT id FROM subscriptions WHERE provider_subscription_id = {mark}",
            (provider_subscription_id,),
        )
        row = cur.fetchone()
        if row:
            cur.execute(
                f"UPDATE subscriptions SET plan = {mark}, status = {mark}, "
                f"current_period_end = {mark}, updated_at = {mark} WHERE id = {mark}",
                (plan, status, current_period_end, now, row[0]),
            )
        else:
            cur.execute(
                f"INSERT INTO subscriptions (user_id, provider, provider_customer_id, "
                f"provider_subscription_id, plan, status, current_period_end, created_at, updated_at) "
                f"VALUES ({_ph(9)})",
                (user_id, provider, provider_customer_id, provider_subscription_id,
                 plan, status, current_period_end, now, now),
            )


