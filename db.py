def get_classroom_plays(game, cohort=None, limit=500):
    """Most recent plays of one game, newest first, detail_json parsed.
    Aggregation into game-specific stats happens in server.py — this layer
    just fetches and deserializes, it doesn't know what a 'sent' or an
    'offer' means for any particular game. When `cohort` is given, only
    plays tagged with that exact code are returned."""
    mark = "%s" if IS_POSTGRES else "?"
    with _conn() as conn:
        cur = conn.cursor()
        if cohort:
            cur.execute(
                f"SELECT role, archetype, detail_json, created_at FROM classroom_plays "
                f"WHERE game = {mark} AND cohort = {mark} ORDER BY created_at DESC LIMIT {mark}",
                (game, cohort, limit),
            )
        else:
            cur.execute(
                f"SELECT role, archetype, detail_json, created_at FROM classroom_plays "
                f"WHERE game = {mark} ORDER BY created_at DESC LIMIT {mark}",
                (game, limit),
            )
        rows = cur.fetchall()
    plays = []
    for role, archetype, detail_json, created_at in rows:
        try:
            detail = json.loads(detail_json)
        except (TypeError, ValueError):
            detail = {}
        plays.append({"role": role, "archetype": archetype, "detail": detail, "created_at": created_at})
    return plays


