def log_choice(user_id, persona, difficulty, choice, homeostasis=None):
    """
    Records one decision. `homeostasis` optionally carries the PIPE telemetry
    for that decision so behaviour can be analysed over time:
      decision_index, wellbeing, zone, archetype_expected, gap,
      trigger_kind, characteristic_drift, session_id
    """
    h = homeostasis or {}

    def _int(v):
        try:
            return int(v)
        except (TypeError, ValueError):
            return None

    def _float(v):
        try:
            return float(v)
        except (TypeError, ValueError):
            return None

    with _conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"""INSERT INTO scenario_choices
                (user_id, persona, difficulty, choice, decision_index, wellbeing,
                 zone, archetype_expected, gap, trigger_kind, characteristic_drift,
                 session_id, principle, surface, dlo_band, dlo_score, titration,
                 predicted, prediction_correct, confidence, surprise, c_level,
                 primary_axis, created_at)
                VALUES ({_ph(24)})""",
            (
                user_id,
                str(persona)[:64],
                str(difficulty)[:16],
                str(choice)[:200],
                _int(h.get("decision_index")),
                _int(h.get("wellbeing")),
                (str(h.get("zone"))[:16] if h.get("zone") else None),
                _int(h.get("archetype_expected")),
                _int(h.get("gap")),
                (str(h.get("trigger_kind"))[:16] if h.get("trigger_kind") else None),
                (1 if h.get("characteristic_drift") else 0) if h.get("characteristic_drift") is not None else None,
                (str(h.get("session_id"))[:64] if h.get("session_id") else None),
                (str(h.get("principle"))[:64] if h.get("principle") else None),
                (str(h.get("surface"))[:64] if h.get("surface") else None),
                (str(h.get("dlo_band"))[:16] if h.get("dlo_band") else None),
                _float(h.get("dlo_score")),
                (str(h.get("titration"))[:16] if h.get("titration") else None),
                _int(h.get("predicted")),
                (1 if h.get("prediction_correct") else 0) if h.get("prediction_correct") is not None else None,
                _float(h.get("confidence")),
                _int(h.get("surprise")),
                (str(h.get("c_level"))[:8] if h.get("c_level") else None),
                (str(h.get("primary_axis"))[:32] if h.get("primary_axis") else None),
                time.time(),
            ),
        )


