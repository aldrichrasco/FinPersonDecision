"""
Database layer for FinPerson.

Uses Postgres when DATABASE_URL is set (Render provides this automatically
when you attach a Postgres instance), and falls back to a local SQLite file
for development so `python server.py` works with zero setup.

Both paths expose the same three functions the app needs:
    get_or_create_user(google_sub, name, email, picture) -> user dict
    get_state(user_id)  -> dict or None
    save_state(user_id, state_dict)
    log_choice(user_id, persona, difficulty, choice)
"""

import json
import os
