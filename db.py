def _existing_columns(cur, table):
    if IS_POSTGRES:
        cur.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = %s",
            (table,),
        )
        return {r[0] for r in cur.fetchall()}
    cur.execute(f"PRAGMA table_info({table})")
    return {r[1] for r in cur.fetchall()}


def _migrate():
    """Add any missing columns. Safe to run on every boot."""
    with _conn() as conn:
        cur = conn.cursor()
        for table, col, coltype in _ADDED_COLUMNS:
            try:
                if col not in _existing_columns(cur, table):
                    cur.execute(f"ALTER TABLE {table} ADD COLUMN {col} {coltype}")
            except Exception:
                # A concurrent boot may have added it first; ignore and continue.
                pass


def _now():
    return time.time()


def ensure_research_participant(user_id):
    if not user_id:
        return None
    with _conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"SELECT id, participant_id, consent_status, consent_version, consented_at, withdrawn_at FROM research_participants WHERE user_id = {_ph(1)}",
            (user_id,),
        )
        row = cur.fetchone()
        if row:
            participant_id = row["participant_id"]
            consent_status = row["consent_status"]
            consent_version = row["consent_version"]
        else:
            participant_id = f"rp-{secrets.token_hex(6)}"
            cur.execute(
                f"INSERT INTO research_participants (user_id, participant_id, consent_status, consent_version, created_at, updated_at) VALUES ({_ph(6)})",
                (user_id, participant_id, 0, "v1", _now(), _now()),
            )
            cur.execute(
                f"UPDATE users SET research_participant_id = {_ph(1)} WHERE id = {_ph(1)}",
                (participant_id, user_id),
            )
            consent_status = 0
            consent_version = "v1"
        return {
            "user_id": user_id,
            "participant_id": participant_id,
            "consent_status": bool(consent_status),
            "consent_version": consent_version,
        }


def get_research_consent(user_id):
    participant = ensure_research_participant(user_id)
    if not participant:
        return {"consent": False, "participant_id": None, "consent_version": "v1"}
    return {
        "consent": participant["consent_status"],
        "participant_id": participant["participant_id"],
        "consent_version": participant["consent_version"],
    }


def set_research_consent(user_id, consent, source="onboarding", version="v1"):
    participant = ensure_research_participant(user_id)
    if not participant:
        return None
    now = _now()
    with _conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO consent_records (user_id, participant_id, consent_status, consent_version, source, created_at, updated_at) VALUES ({_ph(7)})",
            (user_id, participant["participant_id"], 1 if consent else 0, version, source, now, now),
        )
        cur.execute(
            f"UPDATE research_participants SET consent_status = {_ph(1)}, consent_version = {_ph(1)}, updated_at = {_ph(1)}, consented_at = {_ph(1)}, withdrawn_at = {_ph(1)} WHERE user_id = {_ph(1)}",
            (1 if consent else 0, version, now, now if consent else None, None if consent else now, user_id),
        )
    return get_research_consent(user_id)


def log_assessment_answer(user_id, payload):
    participant = ensure_research_participant(user_id)
    if not participant:
        return None
    now = _now()
    with _conn() as conn:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO assessment_sessions (user_id, participant_id, stage, completed, model_version, created_at, updated_at) VALUES ({_ph(7)})",
            (
                user_id,
                participant["participant_id"],
                payload.get("stage", "free"),
                1 if payload.get("completed") else 0,
                payload.get("model_version", "v1"),
                now,
                now,
            ),
        )
        if IS_POSTGRES:
            cur.execute("SELECT LASTVAL()")
            session_id = cur.fetchone()[0]
        else:
            session_id = cur.lastrowid
        cur.execute(
            f"INSERT INTO assessment_answers (session_id, question_key, answer, score, model_version, created_at) VALUES ({_ph(6)})",
            (
                session_id,
                payload.get("question_key") or payload.get("question") or "question",
                json.dumps(payload.get("answer")) if isinstance(payload.get("answer"), (dict, list)) else payload.get("answer"),
                payload.get("score"),
                payload.get("model_version", "v1"),
                now,
            ),
        )
    return {"session_id": session_id, "participant_id": participant["participant_id"]}


